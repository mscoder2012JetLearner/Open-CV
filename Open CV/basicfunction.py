import cv2
import numpy as np
image1=cv2.imread(r"C:\Users\maxsc\Open CV\images\foretspath.jpg")
cv2.imshow("image1",image1)
cv2.waitKey(0)
image2=cv2.imread(r"C:\Users\maxsc\Open CV\images\sunset.webp")
cv2.imshow("image2",image2)
cv2.waitKey(0)
resizeimage1=cv2.resize(image1,(600,900))
cv2.imshow("resized",resizeimage1)
cv2.waitKey(0)
addedimage1=cv2.addWeighted(resizeimage1,0.3,image2,0.7,0)
cv2.imshow("added1",addedimage1)
cv2.waitKey(0)
addedimage2=cv2.addWeighted(resizeimage1,0.7,image2,0.3,0)
cv2.imshow("added2",addedimage2)
cv2.waitKey(0)
addedimage3=cv2.addWeighted(resizeimage1,0.5,image2,0.5,0)
cv2.imshow("added3",addedimage3)
cv2.waitKey(0)
subtractimage1=cv2.subtract(resizeimage1,image2)
cv2.imshow("subtract1",subtractimage1)
cv2.waitKey(0)
subtractimage2=cv2.subtract(image2,resizeimage1)
cv2.imshow("subtract2",subtractimage2)
cv2.waitKey(0)
kernal1=np.ones((3,3),np.uint8)
erorodedimage1=cv2.erode(resizeimage1,kernal1)
cv2.imshow("eroded",erorodedimage1)
cv2.waitKey(0)